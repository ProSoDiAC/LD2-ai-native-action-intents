#!/usr/bin/env python3
"""
Write (or check) the SHA-256 manifest of every result file behind the manuscript.

    python3 experiments/write_results_manifest.py            # write paper2_results_manifest.json
    python3 experiments/write_results_manifest.py --check    # compare, exit 1 on mismatch

"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from pathlib import Path

RESULTS = Path(__file__).resolve().parent / "results"
MANIFEST = RESULTS / "paper2_results_manifest.json"
SKIP = {MANIFEST.name}
SUFFIXES = {".json", ".jsonl", ".csv", ".log"}


def collect() -> dict[str, dict]:
    out = {}
    for p in sorted(RESULTS.rglob("*")):
        if not p.is_file() or p.name in SKIP or p.suffix not in SUFFIXES or "figures" in p.parts:
            continue
        rel = p.relative_to(RESULTS).as_posix()
        out[rel] = {"sha256": hashlib.sha256(p.read_bytes()).hexdigest(), "bytes": p.stat().st_size}
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--committed-only", action="store_true",
                        help="with --check: skip the regenerable per-trial files, which are not "
                             "tracked in git (used by CI on a fresh checkout)")
    args = parser.parse_args()
    current = collect()
    if args.check:
        ref = json.loads(MANIFEST.read_text())["artifacts"]
        if args.committed_only:
            ref = {k: v for k, v in ref.items() if "_trials" not in Path(k).name}
        bad = sorted(k for k in ref if current.get(k, {}).get("sha256") != ref[k]["sha256"])
        missing = sorted(k for k in ref if k not in current)
        print(f"[manifest] {len(ref) - len(bad)}/{len(ref)} artifacts match {MANIFEST.name}")
        for k in bad:
            print(f"  {'missing' if k in missing else 'differs'}: {k}")
        return 1 if bad else 0
    MANIFEST.write_text(json.dumps({
        "created_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "python": sys.version.split()[0],
        "note": "Live-stack and GPU artifacts (b2_fidelity_seed*, gate_latency_run*, "
                "perception_cache/*) are archived measurements, not regenerated by "
                "reproduce_paper2_offline.sh; *_trials* files are regenerated and not tracked.",
        "artifacts": current,
    }, indent=2))
    print(f"[manifest] wrote {MANIFEST} ({len(current)} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
